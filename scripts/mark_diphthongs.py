SILENT_U_RE = re.compile(r"(?i)(?:q|g)u(?=[eéií])")

WORD_RE = re.compile(r"[A-Za-zÁÉÍÓÚÜÑáéíóúüñ]+(?:'[A-Za-zÁÉÍÓÚÜÑáéíóúüñ]+)?")

SPANISH_HINT = re.compile(r"[áéíóúüñÁÉÍÓÚÜÑ¿¡]")

