def is_pronunciation_guide(word: str) -> bool:
    if "-" in word:
        return True
    letters = re.sub(r"[^A-Za-zÁÉÍÓÚÜÑáéíóúüñ]", "", word)
    if letters and letters == letters.upper() and len(letters) <= 12:
        if not SPANISH_HINT.search(word) and re.fullmatch(r"[A-Z]+", letters):
            return True
    return False


def word_is_spanish_context(word: str) -> bool:
    low = word.lower()
    if low in ENGLISH_SKIP:
        return False
    if is_pronunciation_guide(word):
        return False
    if SPANISH_HINT.search(word):
        return True
    if low in SPANISH_DIPHTHONG_WORDS:
        return True
    if re.search(
        r"(?i)(ción|sión|dad|tad|mente|idad|ando|iendo|arse|erse|irse|"
        r"amos|emos|imos|áis|éis|aba|aban|aste|aron|ido|ada|ados|adas)$",
        word,
    ):
        return True
    return False


def blocked_ranges(word: str) -> list[tuple[int, int]]:
    """Index ranges that must not be marked as diphthongs."""
    blocked: list[tuple[int, int]] = []
    # Hiatus clusters
    for m in HIATUS_RE.finditer(word):
        blocked.append((m.start(), m.end()))
    # Silent u in que/qui/gue/gui: block the "u" + following weak/strong vowel pair
    # e.g. guerra: positions of "ue"; queso: "ue"; guitarra: "ui"
    for m in SILENT_U_RE.finditer(word):
        # m is q/g + u looking ahead at e/i; block from u through that vowel
        u_index = m.end() - 1  # the 'u'
        # vowel is next char
        if u_index + 1 < len(word):
            blocked.append((u_index, u_index + 2))
    return blocked


def overlaps(a: tuple[int, int], b: tuple[int, int]) -> bool:
    return not (a[1] <= b[0] or b[1] <= a[0])


def find_diphthong_spans(word: str) -> list[tuple[int, int]]:
    """Return non-overlapping (start, end) spans of spoken diphthongs in word."""
    if not word_is_spanish_context(word):
        return []

    blocked = blocked_ranges(word)
    candidates: list[tuple[int, int]] = []
    for m in DIPHTHONG_FIND_RE.finditer(word):
        span = (m.start(), m.end())
        if any(overlaps(span, b) for b in blocked):
            continue
        candidates.append(span)

    # Greedy non-overlapping left-to-right (patterns already longest-first in alternation)
    candidates.sort(key=lambda s: (s[0], -(s[1] - s[0])))
    chosen: list[tuple[int, int]] = []
    for span in candidates:
        if any(overlaps(span, c) for c in chosen):
            continue
        chosen.append(span)
    chosen.sort(key=lambda s: s[0])
    return chosen


def wrap_spans_in_word(word: str) -> str:
    spans = find_diphthong_spans(word)
    if not spans:
        return word
    parts: list[str] = []
    i = 0
    for start, end in spans:
        parts.append(word[i:start])
        parts.append(f'<span class="diphthong">{word[start:end]}</span>')
        i = end
    parts.append(word[i:])
    return "".join(parts)


def unwrap_existing(text: str) -> str:
    # Remove diphthong spans (possibly nested leftover full-word marks)
    prev = None
    while prev != text:
        prev = text
        text = re.sub(
            r'<span class="diphthong">([^<]*)</span>',
            r"\1",
            text,
        )
    return text


def process_text(text: str) -> tuple[str, int]:
    count = 0
    parts = re.split(r"(<[^>]+>)", text)
    out: list[str] = []
    in_diphthong_span = 0

    for part in parts:
        if part.startswith("<"):
            if re.match(r'(?i)<span\b[^>]*class=["\'][^"\']*\bdiphthong\b', part):
                in_diphthong_span += 1
            elif re.match(r"(?i)</span\s*>", part) and in_diphthong_span:
                in_diphthong_span = max(0, in_diphthong_span - 1)
            out.append(part)
            continue
        if in_diphthong_span:
            out.append(part)
            continue

        def repl(m: re.Match) -> str:
            nonlocal count
            w = m.group(0)
            spans = find_diphthong_spans(w)
            if not spans:
                return w
            count += len(spans)
            return wrap_spans_in_word(w)

        out.append(WORD_RE.sub(repl, part))

    return "".join(out), count


def main() -> None:
    raw = TARGET.read_text(encoding="utf-8")
    cleaned = unwrap_existing(raw)
    updated, n = process_text(cleaned)
    TARGET.write_text(updated, encoding="utf-8")
    print(f"Marked {n} diphthong letter-clusters in {TARGET.name}")


if __name__ == "__main__":
    main()
